  function pick(list, seed, offset) {
    if (!list || !list.length) return null;
    return list[(seed + offset) % list.length];
  }

  /**
   * cond: { feels, range:[min,max], type, pop, precip, wind, gusts, uv, isDay }
   */
  function build(cond, gender = 'f', seed = 0) {
    const g = W[gender] || W.f;
    const band = bandOf(cond.feels);
    const wet = ['rain', 'storm', 'sleet'].includes(cond.type) || cond.pop >= 60;
    const snowy = cond.type === 'snow';
    const windy = (cond.gusts || 0) >= 12 || (cond.wind || 0) >= 8;
    const cold = cond.feels <= 3;
    const hasOuter = !['warm', 'hot'].includes(band);
    const items = [];

    // Верхняя одежда
    if (hasOuter) {
      let list = g.outer[band];
      if (wet && ['chilly', 'cool', 'mild'].includes(band)) list = g.outer.rain;
      const it = pick(list, seed, 0);
      if (it) items.push({ ...it, tag: band === 'mild' ? 'На вечер' : wet && !cold ? 'Защита от дождя' : 'Верхняя одежда' });
    }

    // Верх
    items.push({ ...pick(g.top[band], seed, 1), tag: 'Верх' });

    // Низ (с сарафаном не нужен)
    const top = items[items.length - 1];
    if (top.t !== 'Сарафан') items.push({ ...pick(g.bottom[band], seed, 2), tag: 'Низ' });

    // Обувь
    let shoes = g.shoes[band];
    if (snowy && !['freeze', 'frost'].includes(band)) shoes = g.shoes.snow;
    else if (wet && !['freeze', 'frost', 'hot'].includes(band)) shoes = g.shoes.rain;
    if (snowy || wet) shoes = shoes.filter((x) => x.t !== 'Угги');
    items.push({ ...pick(shoes, seed, 3), tag: 'Обувь' });

    // Аксессуары
    if (cond.feels <= 5) {
      items.push(cond.feels <= -10
        ? { e: '🧶', t: 'Тёплая шапка-ушанка', d: 'Закрывает уши, в мороз это обязательно.', tag: 'Аксессуар' }
        : { e: '🧶', t: 'Вязаная шапка', d: 'Шерстяная бини закрывает уши.', tag: 'Аксессуар' });
    }
    if (cond.feels <= 5) items.push({ e: '🧣', t: cond.feels <= -10 ? 'Объёмный шарф' : 'Шарф', d: cond.feels <= -10 ? 'Шарф-снуд, которым можно закрыть лицо.' : 'Защитит шею от ветра.', tag: 'Аксессуар' });
    if (cond.feels <= 3) items.push({ e: '🧤', t: cond.feels <= -10 ? 'Тёплые варежки' : 'Перчатки', d: cond.feels <= -10 ? 'Варежки теплее перчаток.' : 'Кожаные или вязаные перчатки.', tag: 'Аксессуар' });
    if ((wet || cond.pop >= 45) && !snowy) {
      items.push(windy
        ? { e: '☂️', t: 'Капюшон или крепкий зонт', d: 'При таком ветре обычный зонт может вывернуть.', tag: `Осадки ${Math.round(cond.pop)}%` }
        : { e: '☂️', t: 'Зонт', d: `Вероятность осадков ${Math.round(cond.pop)}%, лучше взять с собой.`, tag: 'Не забудь' });
    }
    if (cond.isDay && cond.uv >= 3 && ['clear', 'clouds'].includes(cond.type) && !wet) {
      items.push({ e: '🕶️', t: 'Солнцезащитные очки', d: `УФ-индекс ${Math.round(cond.uv)}, без очков будет слепить.`, tag: 'Солнце' });
    }
    if (cond.isDay && cond.feels >= 22 && cond.uv >= 5) {
      items.push({ e: gender === 'f' ? '👒' : '🧢', t: gender === 'f' ? 'Панама или шляпа' : 'Кепка', d: 'Защитит от солнечного удара.', tag: 'Солнце' });
    }
    if (cond.range && cond.range[1] - cond.range[0] >= 8 && ['cold', 'chilly', 'cool', 'mild'].includes(band)) {
      items.push({ ...g.bag, tag: 'Удобство' });
    }

    // Индекс утепления 0–100
    let warmth = ((28 - cond.feels) / 53) * 100 + (windy ? 6 : 0) + (wet ? 4 : 0);
    warmth = Math.max(0, Math.min(100, Math.round(warmth)));

    return {
      band,
      title: TITLES[band],
      message: makeMessage(cond, band, wet, snowy, windy),
      items,
      tips: makeTips(cond, band, wet, snowy, windy, gender),
      warmth,
    };
  }

  function makeMessage(c, band, wet, snowy, windy) {
    const parts = [`Ощущается как ${fmt(c.feels)}`];
    if (snowy) parts.push('идёт снег');
    else if (wet) parts.push('возможен дождь');
    if (windy) parts.push('ветрено');
    const tail = {
      freeze: 'Оденьтесь как можно теплее и не задерживайтесь на улице.',
      frost: 'Понадобятся пуховик и шапка.',
      cold: 'Нужна тёплая куртка или пальто.',
      chilly: 'Наденьте несколько слоёв, лишний можно снять.',
      cool: 'Возьмите лёгкую куртку.',
      mild: 'Можно одеться легко.',
      warm: 'Верхняя одежда не нужна.',
      hot: 'Лучше всего лён и хлопок.',
    }[band];
    return parts.join(', ') + '. ' + tail;
  }

  function makeTips(c, band, wet, snowy, windy, gender) {
    const tips = [];
    if (c.range && c.range[1] - c.range[0] >= 7) {
      tips.push(`За день ощущаемая температура изменится от ${fmt(c.range[0])} до ${fmt(c.range[1])}. Одевайтесь слоями, чтобы снять лишнее.`);
    }
    if (windy) tips.push(`Порывы ветра до ${Math.round(c.gusts || c.wind)} м/с. Нужна непродуваемая куртка с капюшоном.`);
    if ((c.type === 'sleet') || ((wet || snowy) && c.feels > -4 && c.feels < 3)) tips.push('Возможен гололёд. Наденьте обувь с рельефной подошвой.');
    if (snowy) tips.push('Идёт снег: в обуви с высоким голенищем ноги останутся сухими.');
    if (wet && !snowy) tips.push('Замша и светлая обувь в дождь быстро портятся, лучше кожа или мембрана.');
    if (c.uv >= 6 && c.isDay) tips.push(`УФ-индекс ${Math.round(c.uv)}: нанесите крем SPF 30 или выше.`);
    if (band === 'hot') tips.push('Возьмите воду. Светлая одежда нагревается на солнце меньше тёмной.');
    if (band === 'freeze' || band === 'frost') tips.push('В сильный мороз больше всего помогают шерстяные носки и термобельё.');
    if (band === 'mild' || band === 'cool') tips.push(gender === 'f' ? 'Подходящий день, чтобы надеть что-то новое из гардероба.' : 'Рубашка, чиносы и кеды подойдут и на работу, и на прогулку.');
    if (!tips.length) tips.push('Погода спокойная, особых советов нет.');
    return tips.slice(0, 4);
  }

  const fmt = (t) => { const v = Math.round(t); return `${v > 0 ? '+' : v < 0 ? '−' : ''}${Math.abs(v)}°`; };

  window.Outfits = { build, bandOf, fmt };
